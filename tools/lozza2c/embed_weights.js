//
// embed_weights.js <quantised.bin> <out.h>
//
// Writes the net weights as a C int16 array for the C build of lozza.
//

'use strict';

const fs = require('fs');

const [src, out] = process.argv.slice(2);

const buf = fs.readFileSync(src);
const w   = new Int16Array(buf.buffer, buf.byteOffset, buf.byteLength >> 1);

let s = '// generated by embed_weights.js from ' + src + ' - do not edit\n\n';
s += 'static const int16_t lozza_weights[' + w.length + '] = {\n';

for (let i = 0; i < w.length; i += 32)
  s += '  ' + Array.from(w.subarray(i, i + 32)).join(',') + ',\n';

s += '};\n';

fs.writeFileSync(out, s);
console.log('embed_weights: ' + w.length + ' int16 weights -> ' + out);
